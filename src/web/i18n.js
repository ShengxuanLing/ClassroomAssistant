'use strict';

// ---------------------------------------------------------------- 语言

const UI_LANGUAGES = ['es', 'ca', 'zh'];

/**
 * 初始界面语言。
 *
 * ``ca.lang`` 是**存储值**, 不是既成事实 —— 它可能是旧版本写的、被手工改过的、
 * 或者来自一个曾经支持更多语言的版本。``setLang()`` 校验了, 初始读取也必须校验:
 * 否则 ``state.lang`` 会是一个非法值, 而它会被
 *   1. 直接发给后端 (``?lang=<非法值>``) —— ``normalize_language()`` 抛错;
 *   2. 直接赋给语言选择器 —— 没有匹配项时浏览器显示第一项,
 *      于是"选择器显示的语言"只是**碰巧**等于 ``t()`` 回落的中文。
 *
 * 校验之后这两条都成立, 且不依赖 index.html 里选项的排列顺序。
 */
function pickInitialLang() {
  const stored = window.localStorage.getItem('ca.lang');
  return UI_LANGUAGES.indexOf(stored) >= 0 ? stored : 'zh';
}


