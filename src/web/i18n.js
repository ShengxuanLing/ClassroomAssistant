/**
 * 解析一条界面文案。两层, 顺序固定:
 *
 * 1. ``I18N[lang]`` 里的符号 key (状态机 / 导航这类可枚举项);
 * 2. ``TRANSLATIONS[lang]`` 里的中文原文;
 * 3. 都不命中 -> 原样返回入参。
 *
 * 第 3 条是刻意的: 中文模式下 TRANSLATIONS 根本不参与, 所以**中文界面与
 * 引入译文表之前逐字节一致**; 缺译的西语/加泰语则退化成中文, 不显示内部 key。
 */
function t(key) {
  const table = I18N[state.lang] || I18N.zh;
  if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
  const fallback = I18N.zh;
  if (Object.prototype.hasOwnProperty.call(fallback, key)) return fallback[key];
  const translated = TRANSLATIONS[state.lang];
  if (translated && Object.prototype.hasOwnProperty.call(translated, key)) {
    return translated[key];
  }
  return key;
}


function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.getAttribute('data-i18n'));
  });
  document.documentElement.lang = state.lang === 'zh' ? 'zh-CN' : state.lang;
  const picker = document.getElementById('ui-language');
  if (picker && picker.value !== state.lang) picker.value = state.lang;
}


function setLang(lang) {
  state.lang = UI_LANGUAGES.indexOf(lang) >= 0 ? lang : 'zh';
  window.localStorage.setItem('ca.lang', state.lang);
}

